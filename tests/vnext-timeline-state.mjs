#!/usr/bin/env node
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import vm from 'node:vm';

const root = resolve(import.meta.dirname, '..'), context = {};
new vm.Script(readFileSync(resolve(root, 'editor/vnext-timeline-state.js'), 'utf8')).runInNewContext(context);
const state = context.EditorVNextTimelineState, scene = { timeline: { tracks: {} } }, key = state.keyForEntity('orb');
assert.equal(state.keyForEffect('scene', 'sample', 'threshold'), 'effect:scene:sample:threshold');
assert.equal(state.keyForController('object', 'orb', 'sampling-grid'), 'controller:object:orb:sampling-grid');
assert.equal(state.keyForController('scene', 'sample', 'edge-rule'), 'controller:scene:sample:edge-rule');
assert.equal(state.track(scene, key).segments.length, 1);
assert.equal(state.split(scene, key, .25).created, true); assert.equal(state.track(scene, key).segments.length, 2);
state.setStep(scene, key, 0, { x: 12 }); assert.equal(scene.timeline.tracks.orb.segments[0].values.x, 12);
state.setLinear(scene, key, 1, { linearKeys:['x','alpha','x'] }); assert.equal(scene.timeline.tracks.orb.segments[1].type, 'linear');assert.equal(scene.timeline.tracks.orb.segments[1].from,undefined,'Linear 不保存陈旧端点快照');assert.deepEqual(Array.from(scene.timeline.tracks.orb.segments[1].linearKeys),['x','alpha']);
assert.equal(state.split(scene, key, .25).created, false, '边界不能产生零长度时段');
const mergeKey = state.keyForEntity('merge-check');
state.split(scene, mergeKey, .3); state.split(scene, mergeKey, .6);
state.setStep(scene, mergeKey, 1, { alpha: .5 });
assert.equal(state.track(scene, mergeKey).segments.length, 3);
state.clearSegment(scene, mergeKey, 1);
assert.equal(state.track(scene, mergeKey).segments.length, 1, '清除唯一参数时段应合并回连续基础段');
state.split(scene, mergeKey, .5); state.setStep(scene, mergeKey, 0, { x: 10 });
state.clearSegment(scene, mergeKey, 1);
assert.equal(state.track(scene, mergeKey).segments.length, 2, '相邻仍有参数值时，清除不应吞掉其有效边界');
const motionKey=state.keyForEntity('motion-check');
state.setStep(scene,motionKey,0,{x:12,'anim.bob.amount':5,'anim.bob.period':2,'anim.spin.speed':30});
assert.equal(state.clearSegmentPrefix(scene,motionKey,0,'anim.bob'),true);
assert.deepEqual(Object.keys(state.track(scene,motionKey).segments[0].values).sort(),['anim.spin.speed','x'],'清除漂浮时序不能影响基础属性和其他动态');
assert.equal(state.clearSegmentPrefix(scene,motionKey,0,'anim.bob'),false,'重复清除不应改变其他属性');
assert.equal(state.clear(scene, key), true); assert.equal(state.clear(scene, key), false);
assert.equal(state.visibility(scene, 'orb', false), null, '读取默认全程可见不能写入空轨道');
assert.equal(state.visibilityAt(scene, 'orb', .6), true);
assert.equal(state.splitVisibility(scene, 'orb', .4).created, true);
assert.equal(scene.timeline.visibility.orb.segments.length, 2);
const alignedKey=state.keyForEntity('aligned');state.splitVisibility(scene,'aligned',.25);state.splitVisibility(scene,'aligned',.75);state.alignTrackToVisibility(scene,alignedKey,'aligned');assert.deepEqual(Array.from(state.track(scene,alignedKey).segments,item=>Array.from(item.f)),[[0,.25],[.25,.75],[.75,1]],'参数覆层写入前必须对齐现有显示时段');
state.setVisibility(scene, 'orb', 1, false);
assert.equal(state.visibilityAt(scene, 'orb', .2), true); assert.equal(state.visibilityAt(scene, 'orb', .8), false);
assert.equal(state.moveVisibilityBoundary(scene, 'orb', 0, .6), true);
assert.deepEqual(Array.from(scene.timeline.visibility.orb.segments, item=>Array.from(item.f)), [[0,.6],[.6,1]]);
assert.equal(state.toggleVisibility(scene, 'orb', .8), true);
assert.equal(scene.timeline.visibility.orb.segments.length, 1, '相邻同状态显示段应自动合并');
assert.equal(state.clearVisibility(scene, 'orb'), true); assert.equal(state.visibilityAt(scene, 'orb', .8), true);
assert.equal(state.sceneSegments(scene,false).length,1);assert.equal(scene.timeline.scenes,undefined,'读取隐式单 Scene 不得写入作品');
const inserted=state.insertScene(scene,0,.35,'开场','before');assert.equal(inserted.name,'开场');assert.equal(state.sceneSegments(scene,false).length,2);assert.equal(state.sceneAt(scene,.1).segment.name,'开场');
assert.equal(state.renameScene(scene,1,'主景'),true);assert.equal(state.sceneSegments(scene,false)[1].name,'主景');
assert.equal(state.moveSceneBoundary(scene,0,.45),true);assert.deepEqual(Array.from(state.sceneSegments(scene,false),item=>Array.from(item.f)),[[0,.45],[.45,1]]);
assert.equal(state.removeScene(scene,0),true);assert.equal(state.sceneSegments(scene,false).length,1);assert.deepEqual(Array.from(state.sceneSegments(scene,false)[0].f),[0,1]);
console.log('✓ vNext Timeline State：显式切分、Step/Linear 写入与轨道清理合同通过');
