#!/usr/bin/env node
import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { chromium } from 'playwright-core';

const root=resolve(import.meta.dirname,'../..');
const edge=[process.env.TOSAMPOOL_EDGE_PATH,'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe','C:\\Program Files\\Microsoft\\Edge\\Application\\msedge.exe'].find(path=>path&&existsSync(path));
if(!edge)throw new Error('找不到 Edge');
const browser=await chromium.launch({executablePath:edge,headless:true});
try{
  const page=await browser.newPage({viewport:{width:1500,height:900}}),errors=[];
  page.on('pageerror',error=>errors.push(String(error)));
  await page.goto(pathToFileURL(resolve(root,'img2asset-v4-classic.html')).href+'?e2e=1',{waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>window.ToSampoolV4Workspace?.hasDocument);
  await page.evaluate(()=>{ToSampoolV4Workspace.createBlank({width:160,height:100,loop:4});ToSampoolV4Workspace.mutate(scene=>scene.entities.push({id:'motion-probe',name:'动态探针',type:'rect',x:20,y:20,w:40,h:30,fill:'#ffffff',scaleX:1,scaleY:1,rot:0,alpha:1,anim:{bob:{amount:8,period:2,angle:90},spin:{speed:30}}}));classicV4View.select('motion-probe');});
  await page.waitForFunction(()=>document.querySelector('#inspector-context .v4-formation-heading'));
  assert.equal(await page.locator('#inspector-context .v4-motion-gallery').count(),0,'初始为基本页');
  assert.equal((await page.locator('#inspector-context .v4-formation-heading').textContent()).trim().startsWith('基本'),true,'成样内容页只显示一个基本标题行');
  assert.equal(await page.locator('#inspector-context .v4-transform-card').count(),1,'基础参数应收在一张变换卡片');
  assert.equal(await page.locator('#inspector-context .v4-transform-card .v4-transform-row').count(),6,'变换卡内按功能行组织');
  await page.locator('#inspector-context .v4-formation-toggle').click();
  assert.equal((await page.locator('#inspector-context .v4-formation-heading').textContent()).trim().startsWith('动态'),true,'图标切换后标题变为动态');
  assert.equal(await page.locator('#inspector-context .v4-motion-card').count(),6,'六种动态卡应常驻');
  const spin=page.locator('#inspector-context .v4-motion-card[data-motion-id="spin"]');
  await spin.click();
  assert.equal(await page.evaluate(()=>!!ToSampoolV4Workspace.current().entities.find(item=>item.id==='motion-probe').anim.spin),true,'选中不改变启用状态');
  const blink=page.locator('#inspector-context .v4-motion-card[data-motion-id="blink"]');await blink.click();
  assert.equal(await page.evaluate(()=>!!ToSampoolV4Workspace.current().entities.find(item=>item.id==='motion-probe').anim.blink),false,'选中未启用卡片不应自动启用');
  await page.locator('#inspector-context .v4-motion-card[data-motion-id="spin"]').click();
  assert.match(await page.locator('#tl-context-note').textContent(),/动态 · 持续旋转 · 显示时段与参数覆层/);
  await page.evaluate(()=>ToSampoolV4Workspace.mutate(scene=>{scene.timeline.tracks['motion-probe']={segments:[{f:[0,1],values:{'anim.bob.amount':6}}]};}));
  const lane=page.locator('#tl-context'),laneBox=await lane.boundingBox();
  await lane.click({position:{x:laneBox.width*.4,y:laneBox.height*.5},modifiers:['Alt']});
  await page.evaluate(()=>classicV4Timeline.seek(.4));
  const whiteCut=()=>page.evaluate(()=>{const canvas=document.querySelector('#tl-context'),ctx=canvas.getContext('2d'),scale=canvas.width/canvas.clientWidth,x=Math.round(canvas.clientWidth*.4*scale);for(let y=Math.round(10*scale);y<=Math.round(17*scale);y++)for(let dx=-2;dx<=2;dx++){const pixel=ctx.getImageData(x+dx,y,1,1).data;if(pixel[0]>220&&pixel[1]>220&&pixel[2]>220)return true;}return false;});
  assert.equal(await whiteCut(),true,'当前动态自己的显示切点应可见');
  await page.locator('#inspector-context .v4-motion-card[data-motion-id="bob"]').click();
  assert.equal(await whiteCut(),false,'旋转动态的切点不得残留在漂浮动态轨');
  await page.locator('#inspector-context .v4-formation-toggle').click();
  assert.equal(await whiteCut(),false,'动态切点不得残留在对象基础轨');
  assert.equal(await page.locator('#btn-timing-mode').evaluate(node=>node.classList.contains('active')),false,'动态参数不能误亮基础属性时序');
  await page.locator('#inspector-context .v4-formation-toggle').click();
  await page.locator('#inspector-context .v4-motion-card[data-motion-id="spin"]').click();
  await page.evaluate(()=>ToSampoolV4Workspace.mutate(scene=>{scene.timeline.tracks['motion-probe']={segments:[{f:[0,1],values:{x:25,'anim.bob.amount':6,'anim.spin.speed':40}}]};}));
  await page.locator('#inspector-context [data-v4-motion-detail="spin"] .v4-motion-timing').click();
  const values=await page.evaluate(()=>ToSampoolV4Workspace.current().timeline.tracks['motion-probe'].segments[0].values);
  assert.equal(values.x,25,'基础属性保持');assert.equal(values['anim.bob.amount'],6,'其他动态保持');assert.equal(values['anim.spin.speed'],undefined,'仅清除当前动态参数');
  await page.locator('#inspector-context [data-v4-motion-detail="spin"] .v4-motion-timing').click();
  const speed=page.locator('#inspector-context [data-v4-motion-detail="spin"] .global-field').filter({hasText:'角速度'}).locator('input');await speed.fill('50');await speed.press('Enter');
  await page.waitForFunction(()=>ToSampoolV4Workspace.current().timeline.tracks['motion-probe'].segments[0].values['anim.spin.speed']===50);
  assert.equal(await page.evaluate(()=>ToSampoolV4Workspace.current().entities.find(item=>item.id==='motion-probe').anim.spin.speed),30,'时序写入不得覆盖基础动态参数');
  await page.locator('#element-inspector-tabs [data-element-inspector="fx"]').click();
  assert.equal((await page.locator('#inspector-context .v4-panel-heading').first().textContent()).trim(),'加样效果');
  await page.locator('#element-inspector-tabs [data-element-inspector="sampling"]').click();
  assert.equal((await page.locator('#inspector-context .v4-panel-heading').first().textContent()).trim(),'采样效果');
  assert.deepEqual(errors,[],'无浏览器异常');
  console.log('✓ 成样动态：切换、六卡、选中/启用分离、合并 TRACK 与局部清除通过');
}finally{await browser.close();}
