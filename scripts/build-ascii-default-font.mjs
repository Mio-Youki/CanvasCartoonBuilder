/* Package an unchanged font as gzip/base64 for lazy file://-safe loading.
 * Compression is a transport wrapper, not a font format/name modification. */
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {resolve} from 'node:path';
import {createHash} from 'node:crypto';
import {gzipSync,gunzipSync,inflateRawSync} from 'node:zlib';
const root=resolve(import.meta.dirname,'..'),directory=resolve(root,'assets/fonts');
const digest='9c699de0d24e482700fa0a08ce3abe58ef2ceaf6173323c77b767c72cd538512';
const destination=resolve(directory,'ChillBitmap16-default.js');
const sevenDigest='155b5448b0378b8ea3846143d85ee0492b0cdc8e33c9cf18740636cc0373c186';
const sevenDestination=resolve(directory,'ChillBitmap7-default.js');
function zipFont(){
  const zip=readFileSync(resolve(root,'.local/ascii-font-vendor/Version-2.400.zip'));
  for(let p=0;p<zip.length-46;p++){
    if(zip.readUInt32LE(p)!==0x02014b50)continue;
    const name=zip.subarray(p+46,p+46+zip.readUInt16LE(p+28)).toString();
    if(name!=='ChillBitmap7x.woff2')continue;
    const offset=zip.readUInt32LE(p+42),start=offset+30+zip.readUInt16LE(offset+26)+zip.readUInt16LE(offset+28);
    const raw=zip.subarray(start,start+zip.readUInt32LE(p+20));
    return zip.readUInt16LE(p+10)===8?inflateRawSync(raw):raw;
  }
  throw Error('Official archive missing ChillBitmap7x.woff2');
}
function checkTransport(file,hash){
  const text=readFileSync(file,'utf8'),data=JSON.parse(text.slice(text.indexOf(' = ')+3).trim().replace(/;$/,''));
  if(createHash('sha256').update(gunzipSync(Buffer.from(data.gzip,'base64'))).digest('hex')!==hash)throw Error('ASCII font checksum mismatch: '+file);
}
if(process.argv.includes('--check')){
  checkTransport(sevenDestination,sevenDigest);
  const text=readFileSync(destination,'utf8'),data=JSON.parse(text.slice(text.indexOf(' = ')+3).trim().replace(/;$/,''));
  const font=gunzipSync(Buffer.from(data.gzip,'base64'));
  if(createHash('sha256').update(font).digest('hex')!==digest)throw Error('Default ASCII font checksum mismatch');
  console.log('Default ASCII font transport / original bytes verified');
}else{
  const seven=zipFont();
  if(createHash('sha256').update(seven).digest('hex')!==sevenDigest)throw Error('Unexpected official 7px font');
  mkdirSync(directory,{recursive:true});
  writeFileSync(sevenDestination,'/* Unchanged official ChillBitmap7x WOFF2, Version 2.400. See ChillBitmap7-OFL.txt and ChillBitmap7-LICENSE.md. */\nwindow.__TOSAMPOOL_ASCII_FONT_DATA_7__ = '+JSON.stringify({family:'ToSampoolAsciiPixel7',bytes:seven.length,sha256:sevenDigest,source:'https://github.com/Warren2060/ChillBitmap',gzip:gzipSync(seven,{level:9}).toString('base64')})+';\n');
  for(const [source,target] of [['License','ChillBitmap7-OFL.txt'],['LICENSE.md','ChillBitmap7-LICENSE.md']])writeFileSync(resolve(directory,target),readFileSync(resolve(root,'.local/ascii-font-vendor',source)));
  const font=readFileSync(resolve(root,'.local/ascii-font-vendor/ChillBitmap16.ttf'));
  if(createHash('sha256').update(font).digest('hex')!==digest)throw Error('Unexpected font source');
  mkdirSync(directory,{recursive:true});
  const data={family:'ToSampoolAsciiPixel16',originalName:'寒蝉点阵体 16px',version:'1.000',sha256:digest,bytes:font.length,
    source:'https://github.com/jaywcjlove/free-font/blob/main/docs/fonts/寒蝉字型/寒蝉点阵体_16px.ttf',
    blob:'92d559db391e9dafb1dddedf59c6bdabd1571229',gzip:gzipSync(font,{level:9}).toString('base64')};
  writeFileSync(destination,'/* Unchanged ChillBitmap 16px 1.000. Copyright: Roman Czyborra, Paul Hardy, Qianqian Fang et al.\n * Dual OFL-1.1 / GPL-2.0-or-later with GNU Font Embedding Exception.\n * See ChillBitmap16-OFL.txt, ChillBitmap16-LICENSE.md and ChillBitmap16-README.md.\n * Generated by scripts/build-ascii-default-font.mjs; not included in scene exports. */\nwindow.__TOSAMPOOL_ASCII_FONT_DATA__ = '+JSON.stringify(data)+';\n');
  for(const [source,target] of [['License','ChillBitmap16-OFL.txt'],['LICENSE.md','ChillBitmap16-LICENSE.md']])
    writeFileSync(resolve(directory,target),readFileSync(resolve(root,'.local/ascii-font-vendor',source)));
  console.log('Packaged unchanged font',font.length,'bytes; lazy JS',readFileSync(destination).length,'bytes');
}
