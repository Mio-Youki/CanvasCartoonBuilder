#!/usr/bin/env node
/** Generate the read-only Runtime vNext source mirror used by self-contained test pages. */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const runtime = readFileSync(resolve(root, 'home-scene-vnext.js'), 'utf8');
const output = `/* Generated by scripts/build-runtime-vnext-inline.mjs. Do not edit manually. */\nwindow.__TOSAMPOOL_RUNTIME_VNEXT_SOURCE__ = ${JSON.stringify(runtime)};\n`;
const target = resolve(root, 'runtime-vnext-inline.js');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('runtime-vnext-inline.js 已过期；请运行 node scripts/build-runtime-vnext-inline.mjs');
  console.log('Runtime vNext inline mirror is current');
} else {
  writeFileSync(target, output, 'utf8');
  console.log(`Wrote ${target}`);
}
