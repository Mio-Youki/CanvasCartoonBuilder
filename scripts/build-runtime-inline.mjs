#!/usr/bin/env node
/**
 * 生成编辑器的只读 Runtime 源码镜像。
 *
 * file:// 页面可执行外部 <script>，但常拒绝 fetch/XHR 再读取同一文件；
 * 因此“测试场景”需要这一段已执行的文本镜像来生成真正自包含的 HTML。
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const runtimePath = resolve(root, 'home-scene.js');
const kernel = readFileSync(resolve(root, 'editor/sampling-motion-kernel.js'), 'utf8').trim();
const kernelStart = '/* <generated:sampling-motion-kernel> */';
const kernelEnd = '/* </generated:sampling-motion-kernel> */';
let runtime = readFileSync(runtimePath, 'utf8');
const embedded = kernelStart + '\n' + kernel + '\n' + kernelEnd;
if (runtime.includes(kernelStart) && runtime.includes(kernelEnd)) {
  runtime = runtime.slice(0, runtime.indexOf(kernelStart)) + embedded + runtime.slice(runtime.indexOf(kernelEnd) + kernelEnd.length);
} else {
  const strict = "'use strict';";
  const at = runtime.indexOf(strict);
  if (at < 0) throw new Error('home-scene.js 缺少严格模式锚点，无法嵌入 Sampling Motion Kernel');
  runtime = runtime.slice(0, at + strict.length) + '\n\n' + embedded + runtime.slice(at + strict.length);
}
writeFileSync(runtimePath, runtime, 'utf8');
const out = [
  '/* Generated by scripts/build-runtime-inline.mjs. Do not edit manually. */',
  `window.__PATCHARIUM_RUNTIME_SOURCE__ = ${JSON.stringify(runtime)};`,
  '',
].join('\n');
writeFileSync(resolve(root, 'runtime-inline.js'), out, 'utf8');
